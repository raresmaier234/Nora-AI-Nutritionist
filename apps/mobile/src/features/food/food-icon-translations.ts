// German writes compounds as one word ("Vollkornbrot", "Frischkäse"); the last part says what
// the food is.
const GERMAN_HEADS = ['brotchen', 'brot', 'kase', 'milch', 'wurst', 'saft', 'fleisch', 'kuchen', 'suppe', 'schokolade', 'joghurt', 'kekse'];

const MAX_PHRASE_WORDS = Math.max(...Object.keys(FOOD_WORDS).map((key) => key.split(' ').length));

/** Lowercase, accents dropped, ß → ss: "Pâine" -> "paine", "Käse" -> "kase". */
const fold = (s: string) => s.normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase().replace(/ß/g, 'ss');

/**
 * The name with every food word it knows in English, others kept as they are:
 * "Piept de pui la grătar" -> "chicken breast la gratar". Returns "" when nothing was
 * translated, so English names are matched exactly as before.
 */
export function foodWordsInEnglish(name: string): string {
  const words = fold(name).split(/[^a-z0-9]+/).filter(Boolean);
  const out: string[] = [];
  let translated = false;
  for (let i = 0; i < words.length; ) {
    // Longest phrase first: "piept de pui" before "pui".
    let size = Math.min(MAX_PHRASE_WORDS, words.length - i);
    while (size > 0 && !FOOD_WORDS[words.slice(i, i + size).join(' ')]) size -= 1;
    if (size > 0) {
      out.push(FOOD_WORDS[words.slice(i, i + size).join(' ')]);
      translated = true;
      i += size;
    } else {
      const head = GERMAN_HEADS.find((h) => words[i].length > h.length + 2 && words[i].endsWith(h));
      out.push(head ? FOOD_WORDS[head] : words[i]);
      translated ||= !!head;
      i += 1;
    }
  }
  return translated ? out.join(' ') : '';
}
